CREATE TABLE work_items (
    id uuid PRIMARY KEY,
    number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
    title varchar(180) NOT NULL,
    description text NOT NULL DEFAULT '',
    kind varchar(24) NOT NULL CHECK (kind IN ('improvement','corrective','testing','rewrite')),
    priority varchar(24) NOT NULL CHECK (priority IN ('low','medium','high','critical')),
    status varchar(32) NOT NULL DEFAULT 'backlog' CHECK (status IN ('backlog','in_progress','in_qa','changes_requested','done')),
    assignee varchar(120) NOT NULL DEFAULT '',
    reviewer varchar(120) NOT NULL DEFAULT '',
    reference varchar(120) NOT NULL DEFAULT '',
    event_codes text[] NOT NULL DEFAULT ARRAY[]::text[],
    qa_cycle integer NOT NULL DEFAULT 0,
    return_count integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    completed_at timestamptz
);
CREATE INDEX idx_work_items_kind_status ON work_items(kind,status);
CREATE INDEX idx_work_items_created_at ON work_items(created_at DESC);

CREATE TABLE test_cases (
    id uuid PRIMARY KEY,
    demand_id uuid NOT NULL REFERENCES work_items(id) ON DELETE CASCADE,
    cycle integer NOT NULL CHECK(cycle > 0),
    title varchar(200) NOT NULL,
    steps text NOT NULL DEFAULT '',
    expected text NOT NULL DEFAULT '',
    actual text NOT NULL DEFAULT '',
    result varchar(10) NOT NULL CHECK(result IN ('passed','failed')),
    author varchar(120) NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL
);
CREATE INDEX idx_test_cases_demand_cycle ON test_cases(demand_id,cycle);

CREATE TABLE work_item_transitions (
    id uuid PRIMARY KEY,
    demand_id uuid NOT NULL REFERENCES work_items(id) ON DELETE CASCADE,
    from_status varchar(32) NOT NULL,
    to_status varchar(32) NOT NULL,
    actor varchar(120) NOT NULL DEFAULT '',
    reason text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL
);
CREATE INDEX idx_transitions_demand_created_at ON work_item_transitions(demand_id,created_at);
